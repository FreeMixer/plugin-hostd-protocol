# src/reply-words.h: the error word of every refusal number the verb table declares a code for (its reply_codes), which
# protocol_parse() writes after the number in a session granted the extension errors. Written from the table, never by
# hand; `make check-generated` is red until it is written again.
#
#   tools/reply-words.py            prints src/reply-words.h
#   tools/reply-words.py --check    exits 1 when src/reply-words.h is not what it prints
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = "protocol/plugin-hostd-protocol.json"
OUT = "src/reply-words.h"


def fail(msg):
    sys.exit(f"reply-words: {msg}")


def header():
    try:
        with open(os.path.join(ROOT, TABLE), encoding="utf-8") as f:
            codes = json.load(f)["reply_codes"]
    except (OSError, ValueError, KeyError) as e:
        fail(f"{TABLE}: {e}")
    if not codes:
        fail(f"{TABLE}: no reply code")
    o = ["/* GENERATED by tools/reply-words.py from protocol/plugin-hostd-protocol.json (reply_codes): do not edit. */",
         "#ifndef REPLY_WORDS_H", "#define REPLY_WORDS_H", "",
         "/* the error word of each refusal number the protocol declares a code for (the extension errors) */",
         "static const struct reply_word { int resp; const char *code; } g_reply_words[] = {"]
    for c in codes:
        if not isinstance(c["resp"], int) or c["resp"] >= 0 or not re.fullmatch(r"[a-z0-9.-]+", c["code"]):
            fail(f"{TABLE}: {c} is no refusal number and code")
        o.append(f'    {{ {c["resp"]}, "{c["code"]}" }},')
    o += ["};", "", "#endif"]
    return "\n".join(o) + "\n"


def main():
    text = header()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        try:
            with open(os.path.join(ROOT, OUT), encoding="utf-8") as f:
                have = f.read()
        except OSError:
            have = None
        if have != text:
            sys.exit(f"{OUT} is not what tools/reply-words.py writes: run make gen")
        print(f"{OUT} is current")
        return
    if len(sys.argv) > 1:
        fail(f"usage: {sys.argv[0]} [--check]")
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
